import { describe, expect, it } from 'vitest';
import { imageMark, pdfLinesToText } from './pdfText';

describe('мітки картинок', () => {
  it('мітка картинки — окремий абзац, не зливається з текстом і не прибирається', () => {
    const text = pdfLinesToText([['Перший рядок тексту', imageMark(0), 'продовження тексту.']]);
    expect(text.split('\n\n')).toEqual(['Перший рядок тексту', imageMark(0), 'продовження тексту.']);
  });
});

describe('pdfLinesToText', () => {
  it('колонтитули, що повторюються, і самотні номери сторінок викидаються', () => {
    const pages = [1, 2, 3, 4].map((n) => ['Назва книжки', `Текст сторінки ${n}.`, String(n)]);
    expect(pdfLinesToText(pages)).toBe('Текст сторінки 1.\n\nТекст сторінки 2.\n\nТекст сторінки 3.\n\nТекст сторінки 4.');
  });

  it('перенос на кінці рядка склеюється; рядки абзацу з\'єднуються пробілом', () => {
    expect(pdfLinesToText([['Це дов-', 'гий абзац, що', 'триває.', 'Новий абзац.']]))
      .toBe('Це довгий абзац, що триває.\n\nНовий абзац.');
  });

  it('абзац переходить через межу сторінки', () => {
    expect(pdfLinesToText([['Початок речення'], ['і його кінець.']])).toBe('Початок речення і його кінець.');
  });

  it('заголовок окремим рядком лишається окремим абзацом, якщо далі велика літера', () => {
    expect(pdfLinesToText([['Глава 1', 'Текст.']])).toBe('Глава 1\n\nТекст.');
  });
});
